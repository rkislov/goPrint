package server

import (
	"fmt"
	"github.com/rkislov/goPrint/internal/queue"
	"net"
	"net/http"
	"net/url"
	"strings"
)

func ValidatePublicURL(value string) error {
	if value == "" {
		return nil
	}
	u, err := url.Parse(value)
	if err != nil || u.Hostname() == "" || u.User != nil || u.Path != "" || u.RawQuery != "" || u.Fragment != "" {
		return fmt.Errorf("public-url must be an origin without path or credentials")
	}
	ip := net.ParseIP(u.Hostname())
	if u.Scheme != "https" && (u.Scheme != "http" || ip == nil || !ip.IsLoopback()) {
		return fmt.Errorf("public-url requires HTTPS (except loopback IP)")
	}
	return nil
}
func (s *Server) baseURL(r *http.Request) string {
	if s.PublicURL != "" {
		return s.PublicURL
	}
	return requestOrigin(r)
}
func shQuote(s string) string { return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'" }
func psQuote(s string) string { return "'" + strings.ReplaceAll(s, "'", "''") + "'" }
func (s *Server) clientRoutes(api *http.ServeMux) {
	api.HandleFunc("GET /api/clients/{id}/{platform}", func(w http.ResponseWriter, r *http.Request) {
		p, err := s.Store.Printer(r.Context(), r.PathValue("id"))
		if err != nil {
			respond(w, nil, err)
			return
		}
		if !queue.Accepts(p, "application/pdf") {
			http.Error(w, "Для автоматической настройки нужен принтер с PPD или прямой поддержкой PDF", 409)
			return
		}
		if _, err := s.defaults(p); err != nil {
			http.Error(w, err.Error(), 409)
			return
		}
		origin := s.baseURL(r)
		if err := ValidatePublicURL(origin); err != nil {
			http.Error(w, "configure public-url", 503)
			return
		}
		ipp := origin + "/ipp/printers/" + p.ID
		queueName := "GoPrint_" + p.ID[:12]
		switch r.PathValue("platform") {
		case "linux.sh":
			scheme := "ipps"
			if strings.HasPrefix(origin, "http:") {
				scheme = "ipp"
			}
			device := scheme + strings.TrimPrefix(strings.TrimPrefix(ipp, "https"), "http")
			w.Header().Set("Content-Type", "text/x-shellscript; charset=utf-8")
			w.Header().Set("Content-Disposition", `attachment; filename="goprint-linux.sh"`)
			fmt.Fprintf(w, `#!/usr/bin/env bash
# SPDX-License-Identifier: Apache-2.0
# Generated by GoPrint. No credentials are embedded.
set -euo pipefail
command -v lpadmin >/dev/null || { echo 'Install CUPS client and daemon using your OS package manager.' >&2; exit 1; }
if [[ $EUID -ne 0 ]]; then echo 'Run this script using sudo to create the local CUPS queue.' >&2; exit 1; fi
lpadmin -p %s -D %s -v %s -m everywhere -o auth-info-required=username,password -E
printf 'Created queue: %%s\n' %s
printf 'Enter your GoPrint credentials when CUPS requests them for a print job.\n'
`, shQuote(queueName), shQuote(p.Name), shQuote(device), shQuote(queueName))
		case "windows.ps1":
			w.Header().Set("Content-Type", "text/plain; charset=utf-8")
			w.Header().Set("Content-Disposition", `attachment; filename="goprint-windows.ps1"`)
			// BOM keeps Cyrillic printer names intact in Windows PowerShell 5.1.
			fmt.Fprintf(w, "\xef\xbb\xbf"+`# SPDX-License-Identifier: Apache-2.0
# Generated by GoPrint. No credentials are embedded.
$ErrorActionPreference = 'Stop'
$command = Get-Command Add-Printer -ErrorAction Stop
if (-not $command.Parameters.ContainsKey('IppURL')) {
    throw 'This Windows version does not support Add-Printer -IppURL. Use a supported Windows IPP client.'
}
$name = %s
$uri = %s
if (Get-Printer -Name $name -ErrorAction SilentlyContinue) {
    throw 'A printer with this name already exists. Verify its port before replacing it.'
}
# Uses the Windows IPP class driver. Never disables TLS or changes driver security policy.
Add-Printer -Name $name -IppURL $uri
Write-Host 'GoPrint queue added. Authentication uses your domain account; automatic Windows SSO is not implemented.'
Write-Host 'Verify authentication and print a test PDF before deploying this script through GPO.'
`, psQuote(queueName+" · "+p.Name), psQuote(ipp))
		default:
			http.NotFound(w, r)
		}
	})
}
